/// Emit a CP2 compute op as a typed `dispatch(...)` call building an
/// `OpInvocation` from the op's operand shape. The generated code traps loudly
/// (via `OpStatus::Unimplemented`) if a not-yet-wired op is reached.
fn vu_stmt(ind: &str, pc: u32, op: VuOp, vd: u8, vs: u8, vt: u8, e: u8, de: u8) -> String {
    let _shape = operand_shape(op); // presence check / documentation
    let _ = OperandRole::VsIndex;
    let variant = vu_variant(op);
    // Build an OpInvocation carrying every field; the op body reads only those
    // its shape declares (vs_index mirrors vs for VRNDN/VRNDP).
    let inv = format!(
        "OpInvocation {{ vd: {vd}, vs: {vs}, vt: {vt}, e: {e}, de: {de}, vs_index: {vs} }}"
    );
    format!(
        "{ind}match dispatch(m.vu(), {variant}, {inv}) {{\n\
         {ind}    OpStatus::Executed => {{}}\n\
         {ind}    OpStatus::Unimplemented(op) => return trap_unknown_vu(0x{pc:04X}, op),\n\
         {ind}}}\n"
    )
}

fn vu_variant(op: VuOp) -> String {
    format!("VuOp::{op:?}")
}

/// Emit an `mtc0` (CP2 DMA / status register write). This is the ONE place the
/// overlay-swap early return can be emitted (a `DO_DMA_READ` into IMEM).
fn emit_mtc0(out: &mut String, ind: &str, rt: u8, cop0: u8, pc: u32, next_pc: u32, _delay: bool) {
    // RSP CP0 register indices (n64brew "RSP Registers"):
    //  0 SP_MEM_ADDR, 1 SP_DRAM_ADDR, 2 SP_RD_LEN, 3 SP_WR_LEN, 4 SP_STATUS,
    //  5 SP_DMA_FULL, 6 SP_DMA_BUSY, 7 SP_SEMAPHORE.
    match cop0 {
        0 => {
            out.push_str(&format!("{ind}let v = m.reg({rt}); m.set_dma_mem(v);\n"));
            out.push_str(&format!("{ind}pc = 0x{next_pc:04X};\n"));
        }
        1 => {
            out.push_str(&format!("{ind}let v = m.reg({rt}); m.set_dma_dram(v);\n"));
            out.push_str(&format!("{ind}pc = 0x{next_pc:04X};\n"));
        }
        2 => {
            // DO_DMA_READ: may trigger an overlay swap.
            out.push_str(&format!(
                "{ind}let v = m.reg({rt});\n\
                 {ind}if let Some(r) = m.dma_read(v) {{ m.ctx.resume_address = 0x{pc:04X}; return r; }}\n"
            ));
            out.push_str(&format!("{ind}pc = 0x{next_pc:04X};\n"));
        }
        3 => {
            out.push_str(&format!("{ind}let v = m.reg({rt}); m.dma_write(v);\n"));
            out.push_str(&format!("{ind}pc = 0x{next_pc:04X};\n"));
        }
        // status / semaphore writes: ignored (RSPRecomp c0_reg_write_action
        // returns "" for these — yielding/semaphore are no-ops in recomp).
        _ => {
            out.push_str(&format!("{ind}pc = 0x{next_pc:04X};\n"));
        }
    }
}

/// The delay-slot form of an mtc0 (DMA effect only, no overlay-swap return).
fn mtc0_effect(rt: u8, cop0: u8) -> String {
    match cop0 {
        0 => format!("{{ let v = m.reg({rt}); m.set_dma_mem(v); }}"),
        1 => format!("{{ let v = m.reg({rt}); m.set_dma_dram(v); }}"),
        2 => format!("{{ let v = m.reg({rt}); let _ = m.dma_read(v); }}"),
        3 => format!("{{ let v = m.reg({rt}); m.dma_write(v); }}"),
        _ => "{}".to_string(),
    }
}
